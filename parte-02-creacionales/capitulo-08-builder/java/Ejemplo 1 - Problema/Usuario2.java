public Usuario(
        String nombre,
        String email,
        String telefono,
        String direccion,
        String ciudad,
        String pais,
        int edad,
        boolean activo) {

    this.nombre = nombre;
    this.email = email;
    this.telefono = telefono;
    this.direccion = direccion;
    this.ciudad = ciudad;
    this.pais = pais;
    this.edad = edad;
    this.activo = activo;
}